# while 문의 맨 처음으로 돌아가기: continue
# 예제: 홀수만 출력하기
a = 0
while a < 10:
    a += 1
    if a % 2 == 0: continue # a가 짝수인 경우 print 하지 않고 다음 루프로 넘어감
    print(a)
# 실행 결과
# 1
# 3
# 5
# 7
# 9


