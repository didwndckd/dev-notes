# while-else 문: while문 조건이 거짓이 되어 정상적으로 끝나면 else 절이 실행되고 break로 빠져나가면 실행되지 않는다.
count = 0
while count < 3:
    print(f"카운트: {count}")
    count += 1
else:
    print("while 문이 정상 종료되었습니다.")
# 실행 결과
# 카운트: 0
# 카운트: 1
# 카운트: 2
# while 문이 정상 종료되었습니다.

count = 0
while count < 5:
    print(f"카운트: {count}")
    if count == 2: break # count가 2일때 while 종료
    count += 1
else:
    print("while 문이 정상 종료 되었습니다.")
# 실행 결과
# 카운트: 0
# 카운트: 1
# 카운트: 2

# 중첩된 while 문
# 예제: 구구단중 2단, 3단
i = 2
while i <= 3:
    j = 1
    while j <= 9:
        print(f"{i} x {j} = {i*j}")
        j += 1
    i += 1
